def normalize_series(series: pd.Series) -> pd.Series:
    """Normalize numeric values to [0, 1], using 0.5 when all values are equal."""
    numeric = pd.to_numeric(series, errors="coerce").fillna(0.0)
    min_value = numeric.min()
    max_value = numeric.max()
    if max_value == min_value:
        return pd.Series([0.5] * len(numeric), index=numeric.index, dtype=float)
    return (numeric - min_value) / (max_value - min_value)


def load_boundary_regions(gpkg_path: Path = OSM_GPKG_PATH) -> gpd.GeoDataFrame:
    """Load observed OSM boundary regions using exact layer and field names."""
    boundaries = read_layer(gpkg_path, BOUNDARY_LAYER)
    require_columns(boundaries, {"osm_id", "name"}, BOUNDARY_LAYER)
    polygons = boundaries[boundaries.geometry.geom_type.isin(["Polygon", "MultiPolygon"])].copy()
    regions = polygons[["osm_id", "name", "geometry"]].rename(
        columns={"osm_id": "region_id", "name": "region_name"}
    )
    regions["region_id"] = regions["region_id"].astype(str)
    regions["region_name"] = regions["region_name"].astype(str)
    return regions[["region_id", "region_name", "geometry"]]


def add_region_area(regions: gpd.GeoDataFrame) -> pd.DataFrame:
    """Calculate region area in square kilometers."""
    metric_regions = projected(regions)
    area = metric_regions[["region_id"]].copy()
    area["region_id"] = area["region_id"].astype(str)
    area["region_area_sq_km"] = metric_regions.geometry.area / 1_000_000
    return area


def read_feature_csv(processed_dir: Path, file_name: str) -> pd.DataFrame:
    """Read a processed feature CSV and normalize region identifiers."""
    path = processed_dir / file_name
    if not path.exists():
        raise FileNotFoundError(f"缺少特征文件：{path}")
    frame = pd.read_csv(path)
    if "region_id" not in frame.columns:
        raise KeyError(f"`{file_name}` 缺少 `region_id` 字段")
    frame["region_id"] = frame["region_id"].astype(str)
    return frame


def build_region_stage_scoring_input(
    *,
    processed_dir: Path = PROCESSED_OSM_REGION_DIR,
    regions: gpd.GeoDataFrame | None = None,
) -> pd.DataFrame:
    """Build area-adjusted regional scoring input from existing OSM boundary features."""
    if regions is None:
        regions = load_boundary_regions()

    base = regions[["region_id", "region_name"]].copy()
    base["region_id"] = base["region_id"].astype(str)
    base = base.merge(add_region_area(regions), on="region_id", how="left")
    for file_name in ["poi_features.csv", "road_features.csv", "landuse_features.csv"]:
        base = base.merge(read_feature_csv(processed_dir, file_name), on="region_id", how="left")

    numeric_columns = [column for column in base.columns if column not in {"region_id", "region_name"}]
    base[numeric_columns] = base[numeric_columns].apply(pd.to_numeric, errors="coerce").fillna(0.0)
    base["region_area_sq_km"] = base["region_area_sq_km"].replace(0, pd.NA).astype("Float64")

    for column in POI_COUNT_COLUMNS:
        base[f"{column.replace('_count', '')}_density"] = (
            pd.to_numeric(base[column], errors="coerce").fillna(0.0) / base["region_area_sq_km"]
        ).fillna(0.0)
    base["intersection_density"] = (
        pd.to_numeric(base["intersection_count"], errors="coerce").fillna(0.0) / base["region_area_sq_km"]
    ).fillna(0.0)
    for column in LANDUSE_AREA_COLUMNS:
        base[f"{column.replace('_area', '')}_share"] = (
            pd.to_numeric(base[column], errors="coerce").fillna(0.0) / (base["region_area_sq_km"] * 1_000_000)
        ).fillna(0.0)
    base["total_poi_count"] = base[POI_COUNT_COLUMNS].sum(axis=1)
    base["area_km2"] = pd.to_numeric(base["region_area_sq_km"], errors="coerce").fillna(0.0)
    base["poi_density"] = (
        pd.to_numeric(base["total_poi_count"], errors="coerce").fillna(0.0)
        / base["region_area_sq_km"].replace(0, pd.NA)
    ).fillna(0.0)
    base["residential_landuse_ratio"] = base["residential_share"]
    base["commercial_landuse_ratio"] = base["commercial_share"]
    base["retail_landuse_ratio"] = base["retail_share"]
    base = add_spatial_indicators(base)
    return base


def add_spatial_indicators(frame: pd.DataFrame) -> pd.DataFrame:
    """Add current data-supported spatial scoring indicators."""
    result = frame.copy()
    normalized = pd.DataFrame(index=result.index)
    source_columns = [
        "road_density",
        "intersection_density",
        "bus_stop_density",
        "restaurant_density",
        "convenience_density",
        "supermarket_density",
        "mall_density",
        "school_density",
        "hospital_density",
        "office_density",
        "residential_share",
        "commercial_share",
        "retail_share",
        "industrial_share",
    ]
    for column in source_columns:
        if column not in result.columns:
            result[column] = 0.0
        normalized[column] = normalize_series(result[column])

    result["traffic_accessibility"] = (
        normalized["road_density"] * 0.45
        + normalized["intersection_density"] * 0.30
        + normalized["bus_stop_density"] * 0.25
    )
    competition_pressure = (
        normalized["restaurant_density"] * 0.45
        + normalized["convenience_density"] * 0.30
        + normalized["supermarket_density"] * 0.15
        + normalized["mall_density"] * 0.10
    )
    result["competition_pressure"] = competition_pressure
    result["competition_pressure_reversed"] = 1 - competition_pressure
    result["synergy_business_score"] = (
        normalized["school_density"] * 0.20
        + normalized["hospital_density"] * 0.20
        + normalized["mall_density"] * 0.20
        + normalized["office_density"] * 0.15
        + normalized["residential_share"] * 0.15
        + normalized["commercial_share"] * 0.10
    )
    result["consumption_potential"] = (
        normalized["residential_share"] * 0.30
        + normalized["commercial_share"] * 0.25
        + normalized["retail_share"] * 0.20
        + normalized["supermarket_density"] * 0.15
        + normalized["mall_density"] * 0.10
    )
    result["regional_development"] = (
        normalized["commercial_share"] * 0.30
        + normalized["retail_share"] * 0.25
        + normalized["office_density"] * 0.20
        + normalized["road_density"] * 0.15
        + normalized["industrial_share"] * 0.10
    )
    result["synergy_score"] = result["synergy_business_score"]
    result["development_basis"] = result["regional_development"]
    return result


def weighted_score(frame: pd.DataFrame, weights: dict[str, float], score_column: str) -> pd.Series:
    """Calculate weighted spatial score."""
    missing = [column for column in weights if column not in frame.columns]
    if missing:
        raise KeyError(f"缺少指标字段：{', '.join(missing)}")
    score = pd.Series(0.0, index=frame.index)
    for column, weight in weights.items():
        score += pd.to_numeric(frame[column], errors="coerce").fillna(0.0) * weight
    return score


def score_spatial_business_types(frame: pd.DataFrame) -> pd.DataFrame:
    """Score convenience store and light catering recommendations from spatial indicators."""
    result = frame.copy()
    result["convenience_score"] = weighted_score(result, CONVENIENCE_SPATIAL_WEIGHTS, "convenience_score")
    result["light_catering_score"] = weighted_score(result, LIGHT_CATERING_SPATIAL_WEIGHTS, "light_catering_score")
    result["light_food_score"] = result["light_catering_score"]
    result["rank_convenience"] = result["convenience_score"].rank(ascending=False, method="first").astype(int)
    result["rank_light_catering"] = result["light_catering_score"].rank(ascending=False, method="first").astype(int)

    def advantage(row: pd.Series) -> str:
        key = row[ACTIVE_INDICATORS].astype(float).idxmax()
        return SPATIAL_INDICATOR_LABELS[key]

    def risk(row: pd.Series) -> str:
        key = row[ACTIVE_INDICATORS].astype(float).idxmin()
        return SPATIAL_INDICATOR_LABELS[key]

    result["main_advantage"] = result.apply(advantage, axis=1)
    result["main_risk"] = result.apply(risk, axis=1)
    return result.sort_values(["rank_convenience", "rank_light_catering"]).reset_index(drop=True)


def select_regions_for_grid_stage(
    score_result: pd.DataFrame,
    *,
    top_n: int = 5,
    region_ids: list[str] | None = None,
) -> pd.DataFrame:
    """Select regions for detailed 1km grid scoring."""
    result = score_result.copy()
    result["combined_rank_score"] = result["rank_convenience"] + result["rank_light_catering"]
    if region_ids:
        requested = [str(region_id) for region_id in region_ids]
        missing = sorted(set(requested) - set(result["region_id"].astype(str)))
        if missing:
            raise KeyError(f"指定的 region_id 不存在：{', '.join(missing)}")
        selected = result[result["region_id"].astype(str).isin(requested)].copy()
    else:
        selected = result.sort_values(["combined_rank_score", "rank_convenience", "rank_light_catering"]).head(top_n)
    selected["selection_rank"] = range(1, len(selected) + 1)
    keep_columns = [
        "selection_rank",
        "region_id",
        "region_name",
        "convenience_score",
        "light_catering_score",
        "rank_convenience",
        "rank_light_catering",
        "combined_rank_score",
        "main_advantage",
        "main_risk",
    ]
    return selected[keep_columns].reset_index(drop=True)


def safe_region_token(value: Any) -> str:
    """Make a stable region token for internal grid identifiers."""
    return re.sub(r"[^0-9A-Za-z_]+", "_", str(value)).strip("_") or "region"


def build_metric_evaluation_grid(regions: gpd.GeoDataFrame, grid_size_m: int = 1000) -> gpd.GeoDataFrame:
    """Build square metric evaluation grids inside selected regions."""
    if regions.empty:
        raise ValueError("入选区域为空，无法生成评价网格。")
    metric_regions = projected(regions)
    rows: list[dict[str, Any]] = []
    for _, region in metric_regions.iterrows():
        minx, miny, maxx, maxy = region.geometry.bounds
        serial = 1
        x = minx
        while x < maxx:
            y = miny
            while y < maxy:
                cell = box(x, y, min(x + grid_size_m, maxx), min(y + grid_size_m, maxy))
                clipped = cell.intersection(region.geometry)
                if not clipped.is_empty and clipped.area > 0:
                    parent_id = str(region["region_id"])
                    token = safe_region_token(parent_id)
                    rows.append(
                        {
                            "region_id": f"grid_{token}_{serial:06d}",
                            "grid_region_id": parent_id,
                            "grid_region_name": str(region["region_name"]),
                            "grid_area_sq_km": clipped.area / 1_000_000,
                            "geometry": clipped,
                        }
                    )
                    serial += 1
                y += grid_size_m
            x += grid_size_m

    grid = gpd.GeoDataFrame(rows, geometry="geometry", crs=metric_regions.crs)
    centers = grid.geometry.centroid
    centers_wgs = gpd.GeoSeries(centers, crs=grid.crs).to_crs("EPSG:4326")
    grid["grid_center_lon"] = centers_wgs.x
    grid["grid_center_lat"] = centers_wgs.y
    return grid


def load_grid_poi_sources(gpkg_path: Path = OSM_GPKG_PATH) -> gpd.GeoDataFrame:
    """Load OSM point-like POI sources from exact observed layers."""
    frames: list[gpd.GeoDataFrame] = []
    for layer_name in [POI_POINT_LAYER, TRAFFIC_POINT_LAYER, TRANSPORT_POINT_LAYER]:
        frame = read_layer(gpkg_path, layer_name)
        require_columns(frame, {"fclass"}, layer_name)
        frames.append(frame[["fclass", "geometry"]].copy())
    for layer_name in [POI_AREA_LAYER, TRANSPORT_AREA_LAYER]:
        frame = read_layer(gpkg_path, layer_name)
        require_columns(frame, {"fclass"}, layer_name)
        points = frame[["fclass", "geometry"]].copy()
        points["geometry"] = points.geometry.representative_point()
        frames.append(points)
    return pd.concat(frames, ignore_index=True)


def fast_road_features(roads: gpd.GeoDataFrame, regions: gpd.GeoDataFrame) -> pd.DataFrame:
    """Build road length, density, and intersection count with spatial overlay."""
    require_columns(roads, {"fclass"}, ROAD_LAYER)
    selected = roads.copy()
    selected["road_type"] = selected["fclass"].map(classify_road_type)
    selected = selected[selected["road_type"].ne("")]
    metric_regions = projected(regions)
    metric_regions = metric_regions.copy()
    metric_regions["region_area_sq_km"] = metric_regions.geometry.area / 1_000_000
    result = metric_regions[["region_id", "region_area_sq_km"]].copy()
    result["region_id"] = result["region_id"].astype(str)
    result["road_length_total"] = 0.0
    result["intersection_count"] = 0

    if not selected.empty:
        metric_roads = selected.to_crs(metric_regions.crs)
        clipped = gpd.overlay(
            metric_roads[["geometry"]],
            metric_regions[["region_id", "geometry"]],
            how="intersection",
            keep_geom_type=False,
        )
        if not clipped.empty:
            line_mask = clipped.geometry.geom_type.isin(["LineString", "MultiLineString"])
            clipped = clipped[line_mask].copy()
            if not clipped.empty:
                clipped["segment_length"] = clipped.geometry.length
                lengths = clipped.groupby("region_id")["segment_length"].sum()
                result["road_length_total"] = result["region_id"].map(lengths).fillna(0.0)

                intersection_counts: dict[str, int] = {}
                for region_id, group in clipped.groupby("region_id"):
                    points: dict[tuple[float, float], int] = {}
                    for geometry in group.geometry:
                        lines = list(geometry.geoms) if geometry.geom_type == "MultiLineString" else [geometry]
                        for line in lines:
                            if line.geom_type != "LineString":
                                continue
                            for coordinate in line.coords:
                                key = (round(coordinate[0], 3), round(coordinate[1], 3))
                                points[key] = points.get(key, 0) + 1
                    intersection_counts[str(region_id)] = sum(1 for count in points.values() if count >= 3)
                result["intersection_count"] = result["region_id"].map(intersection_counts).fillna(0).astype(int)

    result["road_density"] = result["road_length_total"] / result["region_area_sq_km"].replace(0, pd.NA)
    result["road_density"] = result["road_density"].fillna(0.0)
    return result[ROAD_OUTPUT_COLUMNS]


def fast_landuse_features(landuse: gpd.GeoDataFrame, regions: gpd.GeoDataFrame) -> pd.DataFrame:
    """Build landuse area by region with spatial overlay."""
    require_columns(landuse, {"fclass"}, LANDUSE_LAYER)
    selected = landuse.copy()
    selected["landuse_feature"] = selected["fclass"].map(LANDUSE_CLASSES).fillna("")
    selected = selected[selected["landuse_feature"].ne("")]
    result = pd.DataFrame({"region_id": regions["region_id"].astype(str)})
    for column in LANDUSE_AREA_COLUMNS:
        result[column] = 0.0
    if selected.empty:
        return result[LANDUSE_OUTPUT_COLUMNS]

    metric_regions = projected(regions)
    metric_landuse = selected.to_crs(metric_regions.crs)
    clipped = gpd.overlay(
        metric_landuse[["landuse_feature", "geometry"]],
        metric_regions[["region_id", "geometry"]],
        how="intersection",
        keep_geom_type=False,
    )
    if clipped.empty:
        return result[LANDUSE_OUTPUT_COLUMNS]
    clipped["area_value"] = clipped.geometry.area
    grouped = clipped.groupby(["region_id", "landuse_feature"])["area_value"].sum()
    for (region_id, feature_column), value in grouped.items():
        if feature_column in result.columns:
            result.loc[result["region_id"].eq(str(region_id)), feature_column] = float(value)
    return result[LANDUSE_OUTPUT_COLUMNS]


def build_grid_stage_features(
    *,
    selected_regions: gpd.GeoDataFrame,
    gpkg_path: Path = OSM_GPKG_PATH,
    grid_size_m: int = 1000,
) -> tuple[gpd.GeoDataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Generate 1km grids and aggregate original OSM features into those grids."""
    grid = build_metric_evaluation_grid(selected_regions, grid_size_m=grid_size_m)
    pois = load_grid_poi_sources(gpkg_path)
    roads = read_layer(gpkg_path, ROAD_LAYER)
    landuse = read_layer(gpkg_path, LANDUSE_LAYER)

    poi_features = classify_poi_counts(pois, grid)
    road_features = fast_road_features(roads, grid)
    landuse_features = fast_landuse_features(landuse, grid)
    return grid, poi_features, road_features, landuse_features


def build_grid_stage_scoring_input(
    grid: gpd.GeoDataFrame,
    poi_features: pd.DataFrame,
    road_features: pd.DataFrame,
    landuse_features: pd.DataFrame,
) -> pd.DataFrame:
    """Build grid scoring input from 1km spatial features."""
    base_columns = [
        "region_id",
        "grid_region_id",
        "grid_region_name",
        "grid_area_sq_km",
        "grid_center_lon",
        "grid_center_lat",
    ]
    base = pd.DataFrame(grid[base_columns].drop(columns=[])).copy()
    base["region_id"] = base["region_id"].astype(str)
    base["grid_id"] = base["region_id"]
    base["parent_region_id"] = base["grid_region_id"].astype(str)
    base["centroid_lon"] = base["grid_center_lon"]
    base["centroid_lat"] = base["grid_center_lat"]
    base["area_km2"] = base["grid_area_sq_km"]
    for frame in [poi_features, road_features, landuse_features]:
        next_frame = frame.copy()
        next_frame["region_id"] = next_frame["region_id"].astype(str)
        base = base.merge(next_frame, on="region_id", how="left")
    numeric_columns = [
        column
        for column in base.columns
        if column not in {"region_id", "grid_id", "grid_region_id", "parent_region_id", "grid_region_name"}
    ]
    base[numeric_columns] = base[numeric_columns].apply(pd.to_numeric, errors="coerce").fillna(0.0)

    for column in POI_COUNT_COLUMNS:
        base[f"{column.replace('_count', '')}_density"] = (
            pd.to_numeric(base[column], errors="coerce").fillna(0.0) / base["grid_area_sq_km"].replace(0, pd.NA)
        ).fillna(0.0)
    base["intersection_density"] = (
        pd.to_numeric(base["intersection_count"], errors="coerce").fillna(0.0)
        / base["grid_area_sq_km"].replace(0, pd.NA)
    ).fillna(0.0)
    for column in LANDUSE_AREA_COLUMNS:
        base[f"{column.replace('_area', '')}_share"] = (
            pd.to_numeric(base[column], errors="coerce").fillna(0.0) / (base["grid_area_sq_km"] * 1_000_000)
        ).fillna(0.0)
    base["region_name"] = base["grid_region_name"].astype(str) + "内评价网格"
    base["total_poi_count"] = base[POI_COUNT_COLUMNS].sum(axis=1)
    base = add_spatial_indicators(base)
    return filter_active_grids(base)


def filter_active_grids(frame: pd.DataFrame) -> pd.DataFrame:
    """Keep grids with observed POI, road, or non-farmland landuse activity."""
    result = frame.copy()
    activity = pd.Series(False, index=result.index)
    for column in COMMERCIAL_ACTIVITY_COLUMNS:
        if column in result.columns:
            activity = activity | pd.to_numeric(result[column], errors="coerce").fillna(0).gt(0)
    return result[activity].reset_index(drop=True)


